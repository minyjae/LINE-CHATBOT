// IsCommand ตรวจว่า text เป็นคำสั่งขอความช่วยเหลือหรือวิธีใช้ bot หรือไม่
// input: text ข้อความดิบจากผู้ใช้ เช่น "เลขามินะช่วยต้วย", "ช่วยด้วย", "help"
// output: true ถ้าพบคำเรียกเลขามินะพร้อมคำว่าช่วย หรือพบ keyword ขอความช่วยเหลือ
func IsCommand(text string) bool {
	lower := strings.ToLower(strings.TrimSpace(text))
	if lower == "" {
		return false
	}

	if strings.Contains(text, "เลขามินะ") && (strings.Contains(text, "ช่วย") || strings.Contains(text, "วิธีใช้")) {
		return true
	}

	return shared.ContainsAny(lower, []string{
		"help",
		"how to use",
		"วิธีใช้",
		"ใช้งานยังไง",
		"ใช้ยังไง",
		"ช่วยด้วย",
		"ช่วยต้วย",
	})
}

